package com.example.jarvis.domain.proactive

import java.util.UUID

/**
 * Priority classification for proactive suggestions.
 */
enum class ProactivePriority {
    LOW,
    MEDIUM,
    HIGH,
    URGENT
}

/**
 * Category reason triggering a proactive suggestion.
 */
enum class ProactiveReason {
    DEADLINE_WARNING,
    OVERDUE_TASK,
    ROUTINE_SUGGESTION,
    IDLE_NEXT_ACTION,
    DUPLICATE_PREVENTION
}

/**
 * Proactive engine decision output.
 */
enum class ProactiveDecision {
    IGNORE,   // Discard completely due to policy/cooldown/preferences
    QUEUE,    // Hold until quiet hours end or schedule allows
    SUGGEST,  // Show subtle suggestion in UI
    NOTIFY    // High priority alert (no actual OS notification issued in code)
}

/**
 * User preferences governing proactive suggestions & anti-spam policy.
 */
data class ProactivePreferences(
    val enabled: Boolean = true,
    val quietHoursStart: Int = 22, // 10 PM
    val quietHoursEnd: Int = 7,    // 7 AM
    val maxNotificationsPerDay: Int = 5,
    val allowTaskSuggestions: Boolean = true,
    val allowDeadlineWarnings: Boolean = true,
    val allowRoutineSuggestions: Boolean = true,
    val cooldownMinutesPerKey: Long = 60L
)

/**
 * Structured proactive suggestion generated by ProactiveEngine.
 */
data class ProactiveSuggestion(
    val id: String = UUID.randomUUID().toString(),
    val title: String,
    val message: String,
    val priority: ProactivePriority = ProactivePriority.MEDIUM,
    val decision: ProactiveDecision = ProactiveDecision.SUGGEST,
    val reason: ProactiveReason = ProactiveReason.IDLE_NEXT_ACTION,
    val actionPayload: Map<String, String> = emptyMap(),
    val timestamp: Long = System.currentTimeMillis(),
    val deduplicationKey: String = title
)
